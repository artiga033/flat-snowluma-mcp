//! One tool per official action, including the official MCP execution layer.
//! OneBot envelopes are preserved; stream results use the official metadata shape.

use crate::catalog::{ActionDoc, Catalog};
use crate::config::Config;
use crate::onebot::OneBotClient;
use crate::stream::StreamLimits;
use crate::{patches, schema, stream, validate};
use rmcp::model::{CallToolResult, ContentBlock, Tool, ToolAnnotations};
use serde_json::{Map, Value, json};
use std::borrow::Cow;
use std::collections::BTreeMap;
use std::sync::Arc;
use tokio::sync::Semaphore;
use tokio_util::sync::CancellationToken;

#[derive(Clone)]
pub struct App {
    pub catalog: &'static Catalog,
    pub client: Option<OneBotClient>,
    pub config: Config,
    limits: StreamLimits,
    active_streams: Arc<Semaphore>,
    tool_index: Arc<BTreeMap<String, usize>>,
    tools: Arc<Vec<Tool>>,
}

impl App {
    pub fn new(
        catalog: &'static Catalog,
        client: Option<OneBotClient>,
        config: Config,
    ) -> Result<Self, crate::error::InitError> {
        let limits = StreamLimits {
            max_stream_bytes: config.max_stream_bytes,
            stream_dir: config.stream_dir.clone(),
            idle: config.timeout,
        };
        let tool_index = catalog
            .actions
            .iter()
            .enumerate()
            .map(|(index, action)| (action.name.clone(), index))
            .collect();
        let mut tools: Vec<_> = catalog
            .actions
            .iter()
            .map(|action| build_tool(catalog, action))
            .collect();
        tools.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(Self {
            catalog,
            client,
            config,
            limits,
            active_streams: Arc::new(Semaphore::new(stream::MAX_ACTIVE_STREAMS)),
            tool_index: Arc::new(tool_index),
            tools: Arc::new(tools),
        })
    }
    pub fn tools(&self) -> &[Tool] {
        &self.tools
    }
    pub fn knows(&self, name: &str) -> bool {
        self.tool_index.contains_key(name)
    }

    pub async fn call(
        &self,
        name: &str,
        arguments: Option<Map<String, Value>>,
        cancel: CancellationToken,
    ) -> CallToolResult {
        let Some(&index) = self.tool_index.get(name) else {
            return error_result(format!(
                "unknown tool `{name}`. Use MCP tools/list to find a SnowLuma tool."
            ));
        };
        let action = &self.catalog.actions[index];
        let mut params = arguments.unwrap_or_default();
        let input_file = match take_execution(action, &mut params) {
            Ok(file) => file,
            Err(message) => return error_result(message),
        };
        let mut checked = params.clone();
        if input_file.is_some() {
            if let Some(field) = stream::UPLOAD_OWNED_FIELDS
                .iter()
                .find(|field| params.contains_key(**field))
            {
                return error_result(format!(
                    "params conflict with MCP-owned transfer field: {field}"
                ));
            }
            // stream_id is generated by the MCP in automatic-upload mode only.
            checked.insert("stream_id".into(), json!("mcp-managed"));
        }
        if let Err(error) = validate::validate(action, &checked) {
            return error_result(error.to_string());
        }
        let Some(client) = &self.client else {
            return error_result(
                "SnowLuma endpoint is not configured; set SNOWLUMA_MCP_ENDPOINT to enable calls."
                    .into(),
            );
        };
        if action.stream {
            let Ok(_slot) = self.active_streams.clone().try_acquire_owned() else {
                return error_result(
                    crate::error::StreamError::TooManyActive {
                        action: name.into(),
                        limit: stream::MAX_ACTIVE_STREAMS,
                    }
                    .to_string(),
                );
            };
            if let Some(path) = input_file {
                let path = match resolve_upload_path(&path, self.config.upload_root.as_deref()) {
                    Ok(path) => path,
                    Err(message) => return error_result(message),
                };
                return match stream::upload_local_file(client, &path, params, &self.limits, &cancel)
                    .await
                {
                    Ok(value) => success_result(value),
                    Err(error) => error_result(error.detail()),
                };
            }
            return match stream::consume(client, name, &params, &self.limits, &cancel).await {
                Ok(result) => success_result(result.to_json()),
                Err(error) => error_result(error.detail()),
            };
        }
        // Like the official MCP, logical OneBot failures stay intact as data;
        // transport/protocol failures set isError. No hidden replay of requests.
        match client.call(name, &params, &cancel).await {
            Ok(envelope) => success_result(envelope.raw),
            Err(error) => error_result(error.to_string()),
        }
    }
}

fn take_execution(
    action: &ActionDoc,
    params: &mut Map<String, Value>,
) -> Result<Option<String>, String> {
    let Some(execution) = params.remove("execution") else {
        return Ok(None);
    };
    let execution = execution.as_object().ok_or("execution 必须是对象。")?;
    if let Some(key) = execution.keys().find(|key| key.as_str() != "input_file") {
        return Err(format!("未知 MCP execution 选项: {key}"));
    }
    let Some(input) = execution.get("input_file") else {
        return Ok(None);
    };
    let input = input
        .as_str()
        .filter(|value| !value.trim().is_empty())
        .ok_or("execution.input_file 必须是非空字符串。")?;
    if action.name != "upload_file_stream" {
        return Err("execution.input_file 仅可用于 upload_file_stream。".into());
    }
    Ok(Some(input.into()))
}

/// Preserve action parameters and layer on the official MCP execution option.
/// The conditional requirement belongs to flattening: generated stream_id is
/// required for manual chunks, but not when execution.input_file is present.
pub fn tool_input_schema(catalog: &Catalog, action: &ActionDoc) -> Value {
    let mut input = schema::input_schema(action);
    if action.name == "upload_file_stream" {
        input["properties"]["execution"] =
            catalog.execution["inputSchema"]["properties"]["execution"].clone();
        let remaining: Vec<_> = input["required"]
            .as_array()
            .into_iter()
            .flatten()
            .filter(|field| **field != json!("stream_id"))
            .cloned()
            .collect();
        if remaining.is_empty() {
            input.as_object_mut().unwrap().remove("required");
        } else {
            input["required"] = json!(remaining);
        }
        // Codemode renders union branches independently of their parent. Repeat
        // the complete properties so both valid modes retain discoverable types.
        let mut manual = input.clone();
        manual["required"] = json!(["stream_id"]);
        let mut automatic = input.clone();
        automatic["required"] = json!(["execution"]);
        automatic["properties"]["execution"]["required"] = json!(["input_file"]);
        input["anyOf"] = json!([manual, automatic]);
    }
    input
}

fn build_tool(catalog: &Catalog, action: &ActionDoc) -> Tool {
    let mut annotations = ToolAnnotations::new().open_world(true);
    annotations.read_only_hint = Some(action.read_only);
    if !action.read_only {
        annotations.destructive_hint = Some(true);
    }
    let input = tool_input_schema(catalog, action)
        .as_object()
        .unwrap()
        .clone();
    let mut tool = Tool::new_with_raw(
        action.name.clone(),
        Some(Cow::Owned(patches::description(action))),
        input,
    );
    tool.annotations = Some(annotations);
    if let Some(returns) = &action.returns_schema {
        tool.output_schema = Some(Arc::new(
            json!({"type": "object", "if": {"properties": {"status": {"const": "ok"}}, "required": ["status"]}, "then": {"properties": {"data": returns}}})
                .as_object()
                .unwrap()
                .clone(),
        ));
    }
    tool
}

pub fn success_result(value: Value) -> CallToolResult {
    let mut result = CallToolResult::success(vec![ContentBlock::text(value.to_string())]);
    result.structured_content = Some(value);
    result
}
pub fn error_result(message: String) -> CallToolResult {
    let value = json!({"error": message});
    let mut result = CallToolResult::error(vec![ContentBlock::text(value.to_string())]);
    result.structured_content = Some(value);
    result
}
fn resolve_upload_path(
    path: &str,
    root: Option<&std::path::Path>,
) -> Result<std::path::PathBuf, String> {
    let root = root
        .ok_or("SNOWLUMA_MCP_UPLOAD_ROOT is not configured; set it to allow uploads.")?
        .canonicalize()
        .map_err(|error| format!("cannot resolve upload root: {error}"))?;
    let path = std::path::Path::new(path)
        .canonicalize()
        .map_err(|error| format!("cannot resolve input_file: {error}"))?;
    if !path.starts_with(&root) || path == root {
        return Err("resolved path is outside the configured upload root".into());
    }
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app() -> App {
        let catalog = Catalog::load().unwrap();
        let config = Config {
            endpoint: None,
            token: None,
            timeout: std::time::Duration::from_secs(30),
            stream_dir: std::env::temp_dir().join("fsmcp-test"),
            upload_root: None,
            max_stream_bytes: 1024,
        };
        App::new(catalog, None, config).unwrap()
    }

    #[test]
    fn declares_one_tool_per_official_action() {
        let app = app();
        let catalog = Catalog::load().unwrap();
        assert_eq!(app.tools().len(), catalog.len());
        assert!(app.knows("get_group_msg_history"));
        assert!(app.knows(".get_word_slices"));
        assert!(app.knows("upload_file_stream"));
        assert!(!app.knows("upload_local_file"));
        assert!(!app.knows("download_to_file"));
        assert!(!app.knows("nope"));
    }

    #[test]
    fn read_only_hint_follows_the_catalog() {
        let app = app();
        let tool = app
            .tools()
            .iter()
            .find(|tool| tool.name == "get_group_msg_history")
            .unwrap();
        assert_eq!(
            tool.annotations.as_ref().unwrap().read_only_hint,
            Some(true)
        );
        let send = app
            .tools()
            .iter()
            .find(|tool| tool.name == "send_group_msg")
            .unwrap();
        assert_eq!(
            send.annotations.as_ref().unwrap().read_only_hint,
            Some(false)
        );
    }

    #[tokio::test]
    async fn unknown_tool_is_a_tool_level_error() {
        let app = app();
        let result = app.call("nope", None, CancellationToken::new()).await;
        assert_eq!(result.is_error, Some(true));
    }

    #[tokio::test]
    async fn validation_errors_surface_before_transport() {
        let app = app();
        let mut args = Map::new();
        args.insert("group_id".to_string(), json!(1));
        args.insert("message_count".to_string(), json!(3));
        let result = app
            .call(
                "get_group_msg_history",
                Some(args),
                CancellationToken::new(),
            )
            .await;
        assert_eq!(result.is_error, Some(true));
        let text = result.content[0].as_text().unwrap().text.clone();
        assert!(text.contains("message_count"));
    }

    #[test]
    fn upload_path_must_stay_inside_root() {
        let dir = std::env::temp_dir();
        let root = dir.canonicalize().unwrap();
        assert!(resolve_upload_path("/etc/hostname", Some(&root)).is_err());
        assert!(resolve_upload_path("x", None).is_err());
    }

    #[test]
    fn every_action_is_reachable_by_its_tool_name() {
        // All canonical actions map one-to-one onto tools.
        let app = app();
        let catalog = Catalog::load().unwrap();
        for action in &catalog.actions {
            let name = crate::names::tool_name(&action.name);
            assert!(app.knows(&name), "{} is not reachable", action.name);
        }
    }

    #[test]
    fn output_schemas_describe_the_envelope_without_altering_official_data() {
        let app = app();
        for action in &app.catalog.actions {
            let tool = app
                .tools()
                .iter()
                .find(|tool| tool.name == action.name)
                .unwrap();
            match &action.returns_schema {
                Some(official) => {
                    let output = tool.output_schema.as_ref().unwrap();
                    assert_eq!(output["type"], json!("object"), "{}", action.name);
                    assert_eq!(
                        output["then"]["properties"]["data"], *official,
                        "{}",
                        action.name
                    );
                }
                None => assert!(tool.output_schema.is_none(), "{}", action.name),
            }
        }
    }

    #[test]
    fn automatic_upload_extends_only_the_execution_layer() {
        let app = app();
        for action in &app.catalog.actions {
            let tool = app
                .tools()
                .iter()
                .find(|tool| tool.name == action.name)
                .unwrap();
            let original = action.input_schema.as_ref().unwrap();
            if action.name != "upload_file_stream" {
                assert_eq!(Value::Object(tool.input_schema.as_ref().clone()), *original);
                continue;
            }
            assert_eq!(
                tool.input_schema["properties"]["execution"],
                app.catalog.execution["inputSchema"]["properties"]["execution"]
            );
            for (name, field) in original["properties"].as_object().unwrap() {
                assert_eq!(tool.input_schema["properties"][name], *field);
            }
            let branches = tool.input_schema["anyOf"].as_array().unwrap();
            assert_eq!(branches.len(), 2);
            for branch in branches {
                assert_eq!(
                    branch["properties"]["execution"]["properties"]["input_file"]["type"],
                    "string"
                );
                for (name, field) in original["properties"].as_object().unwrap() {
                    assert_eq!(branch["properties"][name], *field);
                }
            }
            assert_eq!(branches[0]["required"], json!(["stream_id"]));
            assert_eq!(
                branches[1]["properties"]["execution"]["required"],
                json!(["input_file"])
            );
        }
    }

    #[test]
    fn stream_actions_are_marked_destructive() {
        let app = app();
        let tool = app
            .tools()
            .iter()
            .find(|tool| tool.name == "upload_file_stream")
            .unwrap();
        let annotations = tool.annotations.as_ref().unwrap();
        assert_eq!(annotations.read_only_hint, Some(false));
        assert_eq!(annotations.destructive_hint, Some(true));
    }
}
